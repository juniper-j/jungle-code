void printList(LinkedList *ll){

	ListNode *cur;
	if (ll == NULL)
		return;
	cur = ll->head;

	if (cur == NULL)
		printf("Empty");
	while (cur != NULL)
	{
		printf("%d ", cur->item);
		cur = cur->next;
	}
	printf("\n");
}

// 진영!!! 연결 리스트를 순회하며 모든 노드를 제거(+메모리 해제, 리스트 초기화)하는 함수 removeAllItems
void removeAllItems(LinkedList *ll)		// LinkedList 구조체의 포인터 = 매개변수 ll
{	
	// ListNode의 포인터 cur의 역할: 현재 순회 중인 노드를 가리킴
	ListNode *cur = ll->head;	// cur를 head로 초기화: ll은 연결리스트를 가리키는 포인터. 즉, 연결 리스트의 첫번째 노드(= head 노드)의 주소를 가리킴
	// ListNode의 포인터 tmp의 역할: 삭제 전에 다음 노드를 기억하기 위함
	ListNode *tmp;

	while (cur != NULL){	// 리스트 끝까지 순회
		tmp = cur->next;	// tmp에 cur->next(주소) 저장
		free(cur);			// 펑! free(포인터)는 포인터를 해제하는게 아님. 포인터가 가리키고 있는 메모리 공간(노드)을 해제하는 것 = Heap 메모리에서 할당된 공간을 반환
		cur = tmp;			// tmp가 가리키고 있는 메모리 주소를 cur 포인터에 복사
	}
	// 연결 리스트가 비어 있다면, 
	ll->head = NULL;		// head 포인터를 Null로 초기화
	ll->size = 0;			// 리스트 크기 정보도 0으로 초기화
}	// ll은 Null일까? NO!


ListNode *findNode(LinkedList *ll, int index){

	ListNode *temp;

	if (ll == NULL || index < 0 || index >= ll->size)
		return NULL;

	temp = ll->head;

	if (temp == NULL || index < 0)
		return NULL;

	while (index > 0){
		temp = temp->next;
		if (temp == NULL)
			return NULL;
		index--;
	}

	return temp;
}

int insertNode(LinkedList *ll, int index, int value){

	ListNode *pre, *cur;

	if (ll == NULL || index < 0 || index > ll->size + 1)
		return -1;

	// If empty list or inserting first node, need to update head pointer
	// 진영!!! 
	if (ll->head == NULL || index == 0){
		cur = ll->head;
		ll->head = malloc(sizeof(ListNode));
		ll->head->item = value;
		ll->head->next = cur;
		ll->size++;
		return 0;
	}


	// Find the nodes before and at the target position
	// Create a new node and reconnect the links
	if ((pre = findNode(ll, index - 1)) != NULL){
		cur = pre->next;
		pre->next = malloc(sizeof(ListNode));
		pre->next->item = value;
		pre->next->next = cur;
		ll->size++;
		return 0;
	}

	return -1;
}


int removeNode(LinkedList *ll, int index){

	ListNode *pre, *cur;

	// Highest index we can remove is size-1
	if (ll == NULL || index < 0 || index >= ll->size)
		return -1;

	// If removing first node, need to update head pointer
	if (index == 0){
		cur = ll->head->next;
		free(ll->head);
		ll->head = cur;
		ll->size--;

		return 0;
	}

	// Find the nodes before and after the target position
	// Free the target node and reconnect the links
	if ((pre = findNode(ll, index - 1)) != NULL){

		if (pre->next == NULL)
			return -1;

		cur = pre->next;
		pre->next = cur->next;
		free(cur);
		ll->size--;
		return 0;
	}

	return -1;
}
